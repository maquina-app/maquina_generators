require "rails/generators"
require "rails/generators/migration"

module Maquina
  module Generators
    class OauthGenerator < Rails::Generators::Base
      include Rails::Generators::Migration

      source_root File.expand_path("templates", __dir__)

      TEST_HELP = /^require "rails\/test_help"\n/
      USER_SESSIONS = /^  has_many :sessions, dependent: :destroy\n/
      FLAG_NIL = /^  FLAG = nil$/
      FLAG_NAME = /\A[a-z][a-z0-9_]*\z/
      THROTTLE_LIMIT = 30
      THROTTLE_PERIOD = "1.minute"
      # The general throttle's exemptions, in the two shapes maquina:rack_attack
      # has shipped (the same two maquina:csp_reports extends).
      COUNTED_IP_EXEMPTIONS = /req\.path\.start_with\?\("\/assets", "\/rails\/active_storage"/
      STATIC_FILE_PREFIXES = /(STATIC_FILE_PREFIXES = %w\[)([^\]]*)(\])/
      OAUTH_EXEMPTED = /start_with\?\([^)]*"\/mcp", "\/oauth\/token"|STATIC_FILE_PREFIXES = %w\[[^\]]*\/mcp \/oauth\/token/

      # The people and account the generated tests (and maquina:mcp's) sign in as.
      USER_FIXTURES = {
        "mcp_member" => {"email_address" => "mcp-member@example.com", "name" => "MCP Member", "role" => "member"},
        "mcp_admin" => {"email_address" => "mcp-admin@example.com", "name" => "MCP Admin", "role" => "admin"},
        "mcp_other" => {"email_address" => "mcp-other@example.com", "name" => "MCP Other", "role" => "member"}
      }.freeze

      class_option :prefix, type: :string, default: "/settings",
        desc: "Path the Connected apps page lives under"
      class_option :flag, type: :string, default: nil,
        desc: "Feature flag that gates MCP for a user (Mcp.enabled_for?)"
      class_option :skip_views, type: :boolean, default: false,
        desc: "Skip the consent, error and Connected apps views"
      class_option :quiet, type: :boolean, default: false,
        desc: "Suppress post-install instructions"

      def self.next_migration_number(dirname)
        current = Time.now.utc.strftime("%Y%m%d%H%M%S")
        existing = Dir.glob("#{dirname}/[0-9]*_*.rb").map { |f| File.basename(f).split("_", 2).first }.max
        (existing && existing >= current) ? existing.succ : current
      end

      # 1. The consent screen signs people in through Clave's email code.
      def require_clave
        unless %w[app/models/email_verification.rb app/controllers/concerns/authentication.rb]
            .all? { |path| File.exist?(File.join(destination_root, path)) }
          raise Thor::Error, "maquina:oauth signs people in through Clave. Run `rails g maquina:clave` first."
        end

        return if flag_name.nil? || flag_name.match?(FLAG_NAME)

        raise Thor::Error, "--flag takes a lowercase name such as beta_mcp (got #{options[:flag].inspect})."
      end

      # 2. Models, the CIMD fetcher and the app-owned MCP gate
      def create_models
        copy_file "app/models/oauth_client.rb", "app/models/oauth_client.rb"
        copy_file "app/models/oauth_client/metadata_fetcher.rb", "app/models/oauth_client/metadata_fetcher.rb"
        copy_file "app/models/oauth_authorization_code.rb", "app/models/oauth_authorization_code.rb"
        copy_file "app/models/access_token.rb", "app/models/access_token.rb"
        copy_file "app/models/connected_application.rb", "app/models/connected_application.rb"

        create_mcp_gate
        add_user_associations
      end

      # 3. Controllers
      def create_controllers
        copy_file "app/controllers/oauth/authorization_servers_controller.rb", "app/controllers/oauth/authorization_servers_controller.rb"
        copy_file "app/controllers/oauth/protected_resources_controller.rb", "app/controllers/oauth/protected_resources_controller.rb"
        copy_file "app/controllers/oauth/authorizations_controller.rb", "app/controllers/oauth/authorizations_controller.rb"
        copy_file "app/controllers/oauth/tokens_controller.rb", "app/controllers/oauth/tokens_controller.rb"
        copy_file "app/controllers/oauth/revocations_controller.rb", "app/controllers/oauth/revocations_controller.rb"
        copy_file "app/controllers/connected_applications_controller.rb", "app/controllers/connected_applications_controller.rb"
      end

      # 4. Routes
      def add_routes
        return if File.read(File.join(destination_root, "config/routes.rb")).include?("generated by maquina:oauth")

        route routes_block
      end

      # 5. Migrations
      def add_migrations
        migration_template "migration_create_oauth_clients.rb.tt", "db/migrate/create_oauth_clients.rb"
        migration_template "migration_create_oauth_authorization_codes.rb.tt", "db/migrate/create_oauth_authorization_codes.rb"
        migration_template "migration_create_access_tokens.rb.tt", "db/migrate/create_access_tokens.rb"
      end

      # 6. Views: the consent screen, its error page and Connected apps
      def create_views
        return if options[:skip_views]

        copy_file "app/views/oauth/authorizations/new.html.erb", "app/views/oauth/authorizations/new.html.erb"
        copy_file "app/views/oauth/authorizations/error.html.erb", "app/views/oauth/authorizations/error.html.erb"
        copy_file "app/views/connected_applications/index.html.erb", "app/views/connected_applications/index.html.erb"
      end

      # 7. Locale files
      def create_locale_files
        copy_file "config/locales/oauth.en.yml", "config/locales/oauth.en.yml"
        copy_file "config/locales/oauth.es.yml", "config/locales/oauth.es.yml"
      end

      # 8. Codes and PKCE verifiers stay out of the logs. Tokens already do,
      #    through Rails' default :token filter.
      def filter_parameters
        path = "config/initializers/filter_parameter_logging.rb"
        full_path = File.join(destination_root, path)
        return @filter_pending = true unless File.exist?(full_path)
        return if File.read(full_path).include?(":code_verifier")

        append_to_file path, filter_parameters_snippet
      end

      # 9. Fixtures
      def create_fixtures
        copy_file "test/fixtures/oauth_clients.yml", "test/fixtures/oauth_clients.yml"
        copy_file "test/fixtures/oauth_authorization_codes.yml", "test/fixtures/oauth_authorization_codes.yml"
        copy_file "test/fixtures/access_tokens.yml", "test/fixtures/access_tokens.yml"

        append_fixture "test/fixtures/accounts.yml", "mcp", {"name" => "MCP"}
        USER_FIXTURES.each do |label, attributes|
          append_fixture "test/fixtures/users.yml", label, attributes.merge("account" => "mcp")
        end
      end

      # 10. Test helper and the generated tests
      def create_tests
        template "test/test_helpers/oauth_test_helper.rb.tt", "test/test_helpers/oauth_test_helper.rb"
        copy_file "test/models/oauth_authorization_code_test.rb", "test/models/oauth_authorization_code_test.rb"
        copy_file "test/models/access_token_test.rb", "test/models/access_token_test.rb"
        copy_file "test/models/connected_application_test.rb", "test/models/connected_application_test.rb"
        copy_file "test/integration/oauth_discovery_test.rb", "test/integration/oauth_discovery_test.rb"
        template "test/integration/oauth_authorization_test.rb.tt", "test/integration/oauth_authorization_test.rb"
        copy_file "test/integration/oauth_tokens_test.rb", "test/integration/oauth_tokens_test.rb"
        template "test/integration/connected_applications_test.rb.tt", "test/integration/connected_applications_test.rb"

        path = File.join(destination_root, "test/test_helper.rb")
        return @test_helper_pending = true unless File.exist?(path)

        content = File.read(path)
        return if content.include?(test_helper_require)
        return @test_helper_pending = true unless content.match?(TEST_HELP)

        inject_into_file "test/test_helper.rb", "#{test_helper_require}\n", after: TEST_HELP
      end

      # 11. Rack::Attack: /mcp and /oauth/token leave the per-IP budget, and
      #     token requests get a per-client cap.
      def configure_rack_attack
        path = "config/initializers/rack_attack.rb"
        full_path = File.join(destination_root, path)
        return @rack_attack_pending = true unless File.exist?(full_path)

        content = File.read(full_path)
        unless content.match?(OAUTH_EXEMPTED)
          if content.match?(COUNTED_IP_EXEMPTIONS)
            # The match stops before the call's closing paren, which stays in place.
            gsub_file path, COUNTED_IP_EXEMPTIONS, 'req.path.start_with?("/assets", "/rails/active_storage", "/mcp", "/oauth/token"'
          elsif content.match?(STATIC_FILE_PREFIXES)
            gsub_file path, STATIC_FILE_PREFIXES, "\\1\\2 /mcp /oauth/token\\3"
          else
            @rack_attack_exemption_pending = true
          end
        end

        append_to_file path, token_throttle unless content.include?(%("oauth/token/client"))
      end

      # 12. Post-install message
      def show_post_install
        return if options[:quiet]

        say ""
        say "OAuth for MCP clients has been installed!", :green
        say ""
        say "Next steps:", :yellow
        say "  1. bin/rails db:migrate"
        say "  2. rails g maquina:mcp           # the /mcp server these tokens unlock"
        say "  3. Link to connected_apps_path (#{connected_apps_url_path}) from your settings page"
        say ""
        say "Clients find the server at /.well-known/oauth-authorization-server and"
        say "/.well-known/oauth-protected-resource/mcp; they sign people in at /oauth/authorize."
        say ""
        if flag_name
          say "MCP is behind the #{flag_name} flag. Mcp.enabled_for? (app/models/mcp.rb) reads", :yellow
          say "  credentials features.#{flag_name}, then ENV[\"#{flag_name.upcase}\"]. Tests run with it on."
          say ""
        end
        if @flag_pending
          say "app/models/mcp.rb no longer has the generated FLAG line. Set it by hand:", :yellow
          say "  FLAG = :#{flag_name}"
          say ""
        end
        if options[:skip_views]
          say "Write the views yourself (the generated tests leave out the ones that render them):", :yellow
          say "  app/views/oauth/authorizations/new.html.erb     # consent: Allow / Cancel post decision=allow|deny"
          say "  app/views/oauth/authorizations/error.html.erb   # status 400, @reason"
          say "  app/views/connected_applications/index.html.erb # @connected_applications"
          say ""
        end
        if @user_pending
          say "Add to app/models/user.rb, so deleting a person drops their grants:", :yellow
          say user_associations
          say ""
        end
        if @filter_pending
          say "Keep authorization codes out of the logs (config/initializers/filter_parameter_logging.rb):", :yellow
          say filter_parameters_snippet
          say ""
        end
        if @test_helper_pending
          say "Load the OAuth test helper in test/test_helper.rb, after require \"rails/test_help\":", :yellow
          say "  #{test_helper_require}"
          say ""
        end
        if @rack_attack_pending || @rack_attack_exemption_pending
          say "Rack::Attack (config/initializers/rack_attack.rb):", :yellow
          say "  - leave \"/mcp\" and \"/oauth/token\" out of the per-IP count (counted_ip)"
          say "  - cap token requests per client:" if @rack_attack_pending
          say token_throttle if @rack_attack_pending
          say ""
        end
        say "Optional:", :yellow
        say "  - Edit config/locales/oauth.*.yml to customize the consent and Connected apps copy"
        say "  - Test helpers: pkce_pair, authorize_params, redirect_params (test/test_helpers/oauth_test_helper.rb)"
        say ""
      end

      private

      def migration_version
        "[#{Rails::VERSION::MAJOR}.#{Rails::VERSION::MINOR}]"
      end

      def flag_name
        options[:flag].presence
      end

      def prefix
        path = options[:prefix].to_s.strip.delete_prefix("/").delete_suffix("/")
        path.empty? ? nil : "/#{path}"
      end

      def connected_apps_url_path
        "#{prefix}/connected_apps"
      end

      # Written once: the app owns this file. A later --flag still rewrites the
      # generated FLAG = nil line, the same way maquina:mcp --flag does.
      def create_mcp_gate
        path = "app/models/mcp.rb"
        full_path = File.join(destination_root, path)
        return template("app/models/mcp.rb.tt", path) unless File.exist?(full_path)
        return unless flag_name

        content = File.read(full_path)
        if content.match?(FLAG_NIL)
          gsub_file path, FLAG_NIL, "  FLAG = :#{flag_name}"
        elsif !content.include?("FLAG = :#{flag_name}")
          @flag_pending = true
        end
      end

      # A person's tokens and codes go with them; without these, deleting a
      # user who has connected an app fails on the foreign keys.
      def add_user_associations
        path = "app/models/user.rb"
        full_path = File.join(destination_root, path)
        return @user_pending = true unless File.exist?(full_path)

        content = File.read(full_path)
        return if content.include?("has_many :access_tokens")
        return @user_pending = true unless content.match?(USER_SESSIONS)

        inject_into_file path, user_associations, after: USER_SESSIONS
      end

      def user_associations
        "  has_many :access_tokens, dependent: :delete_all\n" \
          "  has_many :oauth_authorization_codes, dependent: :delete_all\n"
      end

      def routes_block
        connected_apps = %(resources :connected_apps, only: [:index, :destroy], controller: "connected_applications")
        connected_apps = %(scope "#{prefix}" do\n  #{connected_apps}\nend) if prefix

        <<~RUBY
          # OAuth (generated by maquina:oauth)
          get "/.well-known/oauth-authorization-server", to: "oauth/authorization_servers#show", as: :oauth_authorization_server
          get "/.well-known/oauth-protected-resource/mcp", to: "oauth/protected_resources#show", as: :oauth_protected_resource
          get "/oauth/authorize", to: "oauth/authorizations#new", as: :new_oauth_authorization
          post "/oauth/authorize", to: "oauth/authorizations#create", as: :oauth_authorization
          post "/oauth/token", to: "oauth/tokens#create", as: :oauth_token
          post "/oauth/revoke", to: "oauth/revocations#create", as: :oauth_revocation
          #{connected_apps}
        RUBY
      end

      # Appends a fixture under its label unless the label is already there,
      # creating the file when it is missing.
      def append_fixture(path, label, attributes)
        full_path = File.join(destination_root, path)
        entry = "#{label}:\n" + attributes.map { |key, value| "  #{key}: #{value}\n" }.join

        unless File.exist?(full_path)
          create_file path, "# Generated by maquina:oauth.\n\n#{entry}"
          return
        end

        content = File.read(full_path)
        return if content.match?(/^#{Regexp.escape(label)}:/)

        separator = if content.empty?
          ""
        else
          (content.end_with?("\n") ? "\n" : "\n\n")
        end
        append_to_file path, separator + entry
      end

      def test_helper_require
        %(require_relative "test_helpers/oauth_test_helper")
      end

      def filter_parameters_snippet
        <<~RUBY

          # OAuth (maquina:oauth): authorization codes and PKCE verifiers stay out of
          # the request log and out of the redirect that hands a code to a client.
          Rails.application.config.filter_parameters += [:token, /\\Acode\\z/, :code_verifier]
        RUBY
      end

      def token_throttle
        <<~RUBY

          # OAuth (maquina:oauth): /mcp and /oauth/token are out of the per-IP count
          # above. AI clients call from shared cloud addresses, and /mcp has its own
          # per-token rate_limit. Token requests are capped per client instead.
          Rack::Attack.throttle("oauth/token/client", limit: #{THROTTLE_LIMIT}, period: #{THROTTLE_PERIOD}) do |req|
            req.params["client_id"].presence if req.path == "/oauth/token" && req.post?
          end
        RUBY
      end
    end
  end
