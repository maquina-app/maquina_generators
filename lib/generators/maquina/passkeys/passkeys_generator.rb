require "rails/generators"
require "rails/generators/migration"

module Maquina
  module Generators
    class PasskeysGenerator < Rails::Generators::Base
      include Rails::Generators::Migration

      source_root File.expand_path("templates", __dir__)

      GEM_LINE = %(gem "webauthn", "~> 3.4")
      USER_SESSIONS = /^  has_many :sessions, dependent: :destroy\n/
      USER_PRIVATE = /^  private\n/
      SIGN_IN_FORM_END = /^      <% end %>\n/
      EMAIL_AUTOCOMPLETE = %(autocomplete: "email")
      TEST_HELP = /^require "rails\/test_help"\n/
      THROTTLE_LIMIT = 20
      THROTTLE_PERIOD = "1.minute"

      class_option :skip_views, type: :boolean, default: false,
        desc: "Skip view templates and Stimulus controllers"
      class_option :quiet, type: :boolean, default: false,
        desc: "Suppress post-install instructions"

      def self.next_migration_number(dirname)
        current = Time.now.utc.strftime("%Y%m%d%H%M%S")
        existing = Dir.glob("#{dirname}/[0-9]*_*.rb").map { |f| File.basename(f).split("_", 2).first }.max
        (existing && existing >= current) ? existing.succ : current
      end

      # 1. Passkeys sign people in through clave's sessions; the email code
      #    stays as the way to get in without one.
      def require_clave
        return if %w[app/models/email_verification.rb app/controllers/concerns/authentication.rb]
          .all? { |path| File.exist?(File.join(destination_root, path)) }

        raise Thor::Error, "maquina:passkeys adds passkeys to Clave's email-code sign-in. Run `rails g maquina:clave` first."
      end

      # 2. The webauthn gem verifies the ceremonies; the flow stays in the app.
      def add_gem
        gemfile = File.join(destination_root, "Gemfile")
        return unless File.exist?(gemfile)
        return if File.read(gemfile).match?(/^\s*gem ["']webauthn["']/)

        append_to_file "Gemfile", "\n#{GEM_LINE}\n"
      end

      def run_bundle_install
        return unless rails_app?

        Bundler.with_unbundled_env do
          system("bundle install", chdir: destination_root)
        end
      end

      # 3. Relying party
      def create_initializer
        copy_file "config/initializers/webauthn.rb", "config/initializers/webauthn.rb"
      end

      # 4. Models
      def create_models
        copy_file "app/models/passkey.rb", "app/models/passkey.rb"

        path = "app/models/user.rb"
        content = File.read(File.join(destination_root, path))
        return if content.include?("has_many :passkeys")

        if content.match?(USER_SESSIONS) && content.scan(USER_PRIVATE).one?
          inject_into_file path, user_association, after: USER_SESSIONS
          inject_into_file path, user_webauthn_id, before: USER_PRIVATE
        else
          @user_pending = true
        end
      end

      # 5. Controllers
      def create_controllers
        copy_file "app/controllers/concerns/passkey_challenge.rb", "app/controllers/concerns/passkey_challenge.rb"
        copy_file "app/controllers/concerns/passkey_reauthentication.rb", "app/controllers/concerns/passkey_reauthentication.rb"
        copy_file "app/controllers/session/passkey_challenges_controller.rb", "app/controllers/session/passkey_challenges_controller.rb"
        copy_file "app/controllers/session/passkeys_controller.rb", "app/controllers/session/passkeys_controller.rb"
        copy_file "app/controllers/passkey_challenges_controller.rb", "app/controllers/passkey_challenges_controller.rb"
        copy_file "app/controllers/passkeys_controller.rb", "app/controllers/passkeys_controller.rb"
      end

      # 6. Routes
      def add_routes
        return if File.read(File.join(destination_root, "config/routes.rb")).include?("generated by maquina:passkeys")

        route <<~RUBY
          # Passkeys (generated by maquina:passkeys)
          resource :session, only: [] do
            resource :passkey_challenge, only: :create, controller: "session/passkey_challenges"
            resource :passkey, only: :create, controller: "session/passkeys"
          end
          resource :passkey_challenge, only: :create
          resources :passkeys, only: [:index, :create, :update, :destroy]
        RUBY
      end

      # 7. Migrations
      def add_migrations
        migration_template "migration_add_webauthn_id_to_users.rb.tt", "db/migrate/add_webauthn_id_to_users.rb"
        migration_template "migration_create_passkeys.rb.tt", "db/migrate/create_passkeys.rb"
      end

      # 8. Views and Stimulus controllers
      def create_views
        return if options[:skip_views]

        copy_file "app/views/passkeys/index.html.erb", "app/views/passkeys/index.html.erb"
        copy_file "app/views/sessions/_passkey.html.erb", "app/views/sessions/_passkey.html.erb"
        copy_file "app/javascript/controllers/passkey_sign_in_controller.js",
          "app/javascript/controllers/passkey_sign_in_controller.js"
        copy_file "app/javascript/controllers/passkey_registration_controller.js",
          "app/javascript/controllers/passkey_registration_controller.js"

        add_passkey_to_sign_in_page
      end

      # 9. Locale files
      def create_locale_files
        copy_file "config/locales/passkeys.en.yml", "config/locales/passkeys.en.yml"
        copy_file "config/locales/passkeys.es.yml", "config/locales/passkeys.es.yml"
      end

      # 10. Test helper and the flow's integration test
      def create_test_helper
        copy_file "test/test_helpers/webauthn_test_helper.rb", "test/test_helpers/webauthn_test_helper.rb"
        copy_file "test/integration/passkeys_test.rb", "test/integration/passkeys_test.rb"

        path = File.join(destination_root, "test/test_helper.rb")
        return unless File.exist?(path)

        content = File.read(path)
        return if content.include?(test_helper_require)
        return @test_helper_pending = true unless content.match?(TEST_HELP)

        inject_into_file "test/test_helper.rb", "#{test_helper_require}\n", after: TEST_HELP
      end

      # 11. Rack::Attack: the sign-in ceremony gets its own login-style throttle.
      def configure_rack_attack
        path = "config/initializers/rack_attack.rb"
        full_path = File.join(destination_root, path)
        return @rack_attack_pending = true unless File.exist?(full_path)
        return if File.read(full_path).include?(%("passkey/ip"))

        append_to_file path, passkey_throttle
      end

      # 12. Post-install message
      def show_post_install
        return if options[:quiet]

        say ""
        say "Passkeys have been installed!", :green
        say ""
        say "Next steps:", :yellow
        say "  1. bin/rails db:migrate"
        say "  2. Link to passkeys_path from your account or settings page"
        say "  3. Visit /passkeys signed in, add a passkey, and sign in with it at /session/new"
        say ""
        say "Production: passkeys are bound to your domain. Set them before deploying:", :yellow
        say "  WEBAUTHN_RP_ID=example.com"
        say "  WEBAUTHN_ORIGINS=https://example.com"
        say "  (or webauthn: {rp_id:, origins:} in credentials; see config/initializers/webauthn.rb)"
        say ""
        if @user_pending
          say "Add to app/models/user.rb:", :yellow
          say user_association
          say user_webauthn_id
        end
        if @sign_in_pending
          say "Offer passkeys on the sign-in page (app/views/sessions/new.html.erb):", :yellow
          say "  - render the button after the email form:  <%= render \"sessions/passkey\" %>"
          say %(  - let the email field suggest passkeys:     autocomplete: "username webauthn")
          say ""
        end
        if @test_helper_pending
          say "Load the passkey test helper in test/test_helper.rb:", :yellow
          say "  #{test_helper_require}"
          say ""
        end
        if @rack_attack_pending
          say "Throttle passkey sign-in in config/initializers/rack_attack.rb:", :yellow
          say passkey_throttle
          say ""
        end
        say "Optional:", :yellow
        say "  - Serving more than one domain? Publish /.well-known/webauthn (Related Origin Requests)"
        say "  - Edit config/locales/passkeys.*.yml to customize messages"
        say "  - Integration tests: register_passkey and sign_in_with_passkey(user) (test/test_helpers/webauthn_test_helper.rb)"
        say ""
      end

      private

      def rails_app?
        File.exist?(File.join(destination_root, "bin/rails"))
      end

      def migration_version
        "[#{Rails::VERSION::MAJOR}.#{Rails::VERSION::MINOR}]"
      end

      # The button goes after clave's email form, and the email field offers
      # saved passkeys in its autofill. A page that no longer has that shape is
      # left alone and listed after the install.
      def add_passkey_to_sign_in_page
        path = "app/views/sessions/new.html.erb"
        full_path = File.join(destination_root, path)
        return @sign_in_pending = true unless File.exist?(full_path)

        content = File.read(full_path)
        return if content.include?(%(render "sessions/passkey"))
        return @sign_in_pending = true unless content.scan(SIGN_IN_FORM_END).one? && content.include?(EMAIL_AUTOCOMPLETE)

        inject_into_file path, %(\n      <%= render "sessions/passkey" %>\n), after: SIGN_IN_FORM_END
        gsub_file path, EMAIL_AUTOCOMPLETE, %(autocomplete: "username webauthn")
      end

      def test_helper_require
        %(require_relative "test_helpers/webauthn_test_helper")
      end

      def user_association
        "  has_many :passkeys, dependent: :destroy\n"
      end

      def user_webauthn_id
        <<~RUBY.gsub(/^(?=.)/, "  ")
          # The WebAuthn user handle: random and stable, never the id or the email,
          # since authenticators store it and hand it back on every sign-in.
          def webauthn_id
            super || begin
              update_column(:webauthn_id, WebAuthn.generate_user_id)
              super
            end
          end

        RUBY
      end

      def passkey_throttle
        <<~RUBY

          # Passkey sign-in (maquina:passkeys): the challenge and the assertion,
          # counted like the email-code login above. Keyed on the address Rails
          # resolves through trusted proxies, not the proxy hop in req.ip.
          Rack::Attack.throttle("passkey/ip", limit: #{THROTTLE_LIMIT}, period: #{THROTTLE_PERIOD}) do |req|
            (req.env["action_dispatch.remote_ip"]&.to_s || req.ip) if req.path.start_with?("/session/passkey") && req.post?
          end
        RUBY
      end
    end
  end
end
