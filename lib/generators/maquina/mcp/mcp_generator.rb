require "rails/generators"
require_relative "mcp_sibling_tools"
require_relative "../backstage_signin/backstage_signin"

module Maquina
  module Generators
    class McpGenerator < Rails::Generators::Base
      include McpSiblingTools
      include BackstageSignin

      source_root File.expand_path("templates", __dir__)

      TEST_HELP = /^require "rails\/test_help"\n/
      FLAG_NIL = /^  FLAG = nil$/
      FLAG_NAME = /\A[a-z][a-z0-9_]*\z/
      ROUTES_MARKER = "# MCP (generated by maquina:mcp)"

      class_option :flag, type: :string, default: nil,
        desc: "Feature flag that gates MCP (rewrites Mcp::FLAG = nil in app/models/mcp.rb)"
      class_option :prefix, type: :string, default: "/settings",
        desc: "Where maquina:oauth put the Connected apps page (for the post-install message)"
      class_option :skip_views, type: :boolean, default: false,
        desc: "maquina:oauth was run with --skip-views: the flow test skips the consent and Connected apps pages"
      class_option :quiet, type: :boolean, default: false,
        desc: "Suppress post-install instructions"

      # 1. The server authenticates with maquina:oauth's tokens.
      def require_oauth
        unless File.exist?(File.join(destination_root, "app/models/access_token.rb"))
          raise Thor::Error, "maquina:mcp serves tools to clients signed in through maquina:oauth. Run `rails g maquina:oauth` first."
        end
        return if options[:flag].nil? || options[:flag].match?(FLAG_NAME)

        raise Thor::Error, "--flag must be a lowercase name such as beta_mcp, got #{options[:flag].inspect}."
      end

      # 2. The endpoint and its bearer authentication
      def create_controllers
        copy_file "app/controllers/mcp_controller.rb", "app/controllers/mcp_controller.rb"
        copy_file "app/controllers/concerns/mcp_authenticatable.rb", "app/controllers/concerns/mcp_authenticatable.rb"
      end

      # 3. Routes
      def add_routes
        path = File.join(destination_root, "config/routes.rb")
        return @routes_pending = true unless File.exist?(path)
        return if File.read(path).include?(ROUTES_MARKER)

        route mcp_routes
      end

      # 4. CORS for browser-based clients
      def create_cors_initializer
        copy_file "config/initializers/mcp_cors.rb", "config/initializers/mcp_cors.rb"
      end

      # 5. The tool registry. tools/app.rb belongs to the app (and to
      #    maquina:mcp_tool) once written, so it is never overwritten.
      def create_registry
        %w[tools tool_definitions tool_error user_scope].each do |name|
          copy_file "app/models/mcp/#{name}.rb", "app/models/mcp/#{name}.rb"
        end
        return if File.exist?(File.join(destination_root, "app/models/mcp/tools/app.rb"))

        copy_file "app/models/mcp/tools/app.rb", "app/models/mcp/tools/app.rb"
      end

      # 5b. Who sees the admin-only tools: User#backstage_access?, the same
      #     backstage.emails list that opens the backstage.
      def add_backstage_access
        add_backstage_access_to_user
      end

      # 6. Tools from generators that ran before MCP existed
      def install_sibling_tools
        @sibling_tools = backfill_sibling_mcp_tools
      end

      # 7. Feature flag: maquina:oauth wrote Mcp::FLAG; point it at --flag.
      def configure_flag
        return unless options[:flag]

        path = "app/models/mcp.rb"
        full_path = File.join(destination_root, path)
        content = File.exist?(full_path) ? File.read(full_path) : ""
        return if content.include?(flag_line)
        return @flag_pending = true unless content.match?(FLAG_NIL)

        gsub_file path, FLAG_NIL, flag_line
      end

      # 8. Test helper and the generated tests
      def create_tests
        copy_file "test/test_helpers/mcp_test_helper.rb", "test/test_helpers/mcp_test_helper.rb"
        template "test/integration/mcp_flow_test.rb.tt", "test/integration/mcp_flow_test.rb"
        copy_file "test/integration/mcp_conformance_test.rb", "test/integration/mcp_conformance_test.rb"
        template "test/models/mcp/tools_test.rb.tt", "test/models/mcp/tools_test.rb"

        path = File.join(destination_root, "test/test_helper.rb")
        return unless File.exist?(path)

        content = File.read(path)
        return if content.include?(test_helper_require)
        return @test_helper_pending = true unless content.match?(TEST_HELP)

        inject_into_file "test/test_helper.rb", "#{test_helper_require}\n", after: TEST_HELP
      end

      # 9. Post-install message
      def show_post_install
        return if options[:quiet]

        say ""
        say "The MCP server has been installed!", :green
        say ""
        say "Next steps:", :yellow
        say "  1. bin/rails db:migrate (if maquina:oauth's migrations have not run yet)"
        say "  2. bin/rails test test/integration/mcp_flow_test.rb test/integration/mcp_conformance_test.rb test/models/mcp"
        say "  3. Connect a client: bin/dev, then"
        say "       npx @modelcontextprotocol/inspector"
        say "     and connect to http://localhost:3000/mcp (Streamable HTTP). Sign in, allow, call whoami."
        say "  4. People see and revoke their connected apps at #{connected_apps_path}"
        say "  5. Add tools: rails g maquina:mcp_tool list_posts status:enum[draft,published]? limit:integer?"
        say ""
        if @sibling_tools.present?
          say "Installed MCP tools for: #{@sibling_tools.join(", ")} (admin only)", :yellow
          say ""
        end
        say "Admin-only tools are for people on the backstage list (User#backstage_access?):", :yellow
        say "  backstage:"
        say "    emails:"
        say "      - you@example.com"
        say "  in bin/rails credentials:edit. An account's admin role is not enough."
        say ""
        if backstage_signin_pending.any?
          say "Add User.backstage_emails and User#backstage_access? to app/models/user.rb by hand:", :yellow
          say backstage_access_methods
        end
        if options[:flag]
          say "MCP is behind the #{options[:flag]} flag (Mcp.enabled_for? in app/models/mcp.rb). Turn it on with", :yellow
          say "  features: { #{options[:flag]}: true } in credentials, or #{options[:flag].upcase}=true"
          say ""
        end
        if @routes_pending
          say "Add to config/routes.rb:", :yellow
          say mcp_routes.gsub(/^/, "  ")
          say ""
        end
        if @flag_pending
          say "Point the MCP gate at your flag in app/models/mcp.rb:", :yellow
          say "  #{flag_line.strip}"
          say ""
        end
        if @test_helper_pending
          say "Load the MCP test helper in test/test_helper.rb:", :yellow
          say "  #{test_helper_require}"
          say ""
        end
        say "Optional:", :yellow
        say "  - Behind a TLS-terminating proxy, set config.assume_ssl so advertised URLs say https"
        say "  - Rate limit: 120 calls a minute per token (McpController); it needs a real cache store"
        say ""
      end

      private

      def mcp_routes
        <<~RUBY
          #{ROUTES_MARKER}
          post "mcp", to: "mcp#create", as: :mcp
          match "mcp", to: "mcp#method_not_allowed", via: [:get, :delete]
        RUBY
      end

      def flag_line
        "  FLAG = :#{options[:flag]}"
      end

      def connected_apps_path
        "#{options[:prefix].to_s.chomp("/")}/connected_apps"
      end

      def test_helper_require
        %(require_relative "test_helpers/mcp_test_helper")
      end
    end
  end
end
