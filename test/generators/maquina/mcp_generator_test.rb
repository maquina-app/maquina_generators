  test "whoami and argument validation run as written" do
    run_generator

    registry = load_registry(flag: nil)
    scope = Scope.new(User.new("ana@example.com"), %w[read write], true)

    result = registry::Mcp::Tools::App.whoami(scope: scope)
    assert_equal({email: "ana@example.com", scope: "read write", server_version: "0.1.0", protocol_version: "2026-07-28"}, result)

    assert_equal 1, registry::Mcp::Tools::App::DEFINITIONS.size
    definition = registry::Mcp::Tools::App::DEFINITIONS.first
    assert_equal "https://json-schema.org/draft/2020-12/schema", definition[:inputSchema][:$schema]
    assert_equal({readOnlyHint: true}, definition[:annotations])
    assert registry::Mcp::Tools::App::DEFINITIONS.frozen?
    assert_equal [], registry::Mcp::Tools::App::WRITE_TOOLS

    flagged = load_registry(flag: :beta_mcp)
    off = Scope.new(User.new("ana@example.com"), %w[read], false)
    assert_equal({name: "beta_mcp", enabled: false}, flagged::Mcp::Tools::App.whoami(scope: off)[:flag])
  end

  test "arguments are checked for required keys, unknown keys, types and enums" do
    run_generator

    tools = load_registry(flag: nil)::Mcp::Tools
    schema = {
      properties: {status: {type: "string", enum: %w[draft published]}, limit: {type: "integer"}, ratio: {type: "number"},
                   archived: {type: "boolean"}},
      required: ["status"]
    }

    assert_equal({status: "draft", limit: 5}, tools.validate_arguments(schema, {"status" => "draft", "limit" => 5, "ratio" => nil}))
    assert_equal({status: "draft", ratio: 1, archived: false}, tools.validate_arguments(schema, {"status" => "draft", "ratio" => 1, "archived" => false}))
    {
      {} => "Missing required argument: status",
      {"status" => "gone"} => "status must be one of: draft, published",
      {"status" => "draft", "limit" => "5"} => "limit must be of type integer",
      {"status" => "draft", "archived" => "yes"} => "archived must be of type boolean",
      {"status" => "draft", "verbose" => true} => "Unknown argument: verbose"
    }.each do |arguments, message|
      error = assert_raises(tools::InvalidParams) { tools.validate_arguments(schema, arguments) }
      assert_equal message, error.message
    end
    assert_raises(tools::InvalidParams) { tools.validate_arguments(schema, "status=draft") }
    assert_equal({}, tools.validate_arguments({properties: {}, required: []}, nil))
  end

