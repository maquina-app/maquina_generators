  test "the CORS middleware answers preflights and leaves authorize alone" do
    run_generator

    cors = load_cors
    app = ->(_env) { [200, {}, ["ok"]] }
    middleware = cors.new(app)

    status, headers, = middleware.call("PATH_INFO" => "/mcp", "REQUEST_METHOD" => "OPTIONS")
    assert_equal 204, status
    assert_equal "*", headers["access-control-allow-origin"]
    assert_equal "Authorization, Content-Type, MCP-Protocol-Version, Mcp-Method, Mcp-Name",
      headers["access-control-allow-headers"]
    assert_equal "WWW-Authenticate", headers["access-control-expose-headers"]
    assert_nil headers["access-control-allow-credentials"]

    %w[/mcp /oauth/token /oauth/revoke /.well-known/oauth-authorization-server /.well-known/oauth-protected-resource/mcp].each do |path|
      _, headers, = middleware.call("PATH_INFO" => path, "REQUEST_METHOD" => "POST")
      assert_equal "*", headers["access-control-allow-origin"], path
    end
    %w[/oauth/authorize /settings/connected_apps /mcpx /].each do |path|
      _, headers, = middleware.call("PATH_INFO" => path, "REQUEST_METHOD" => "GET")
      assert_nil headers["access-control-allow-origin"], path
    end

    assert_file "config/initializers/mcp_cors.rb", /^Rails\.application\.config\.middleware\.insert_before 0, McpCors$/
  end

