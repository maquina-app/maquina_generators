  def oauth_mcp_model(flag_name: nil)
    ERB.new(File.read(File.join(OAUTH_TEMPLATES, "app/models/mcp.rb.tt")), trim_mode: "-").result(binding)
  end

  # McpController::ERRORS, read from the generated file.
  def controller_errors
    source = File.read(File.join(destination_root, "app/controllers/mcp_controller.rb"))
    eval(source[/^  ERRORS = (\{.*?^  \}\.freeze)$/m, 1], binding, "mcp_controller.rb") # rubocop:disable Security/Eval
  end

  def load_cors
    source = File.read(File.join(destination_root, "config/initializers/mcp_cors.rb"))
    Module.new.tap { |sandbox| sandbox.module_eval(source.sub(/^Rails\.application.*$/, "")) }::McpCors
  end

  # The generated registry files, loaded into a sandbox with the constants
  # app/models/mcp.rb defines.
  def load_registry(flag:)
    Module.new.tap do |sandbox|
      sandbox.module_eval(<<~RUBY, __FILE__, __LINE__ + 1)
        module Mcp
          PROTOCOL_VERSION = "2026-07-28"
          SERVER_VERSION = "0.1.0"
          FLAG = #{flag.inspect}
        end
      RUBY
      %w[tool_error tools tools/app].each do |name|
        sandbox.module_eval(File.read(File.join(destination_root, "app/models/mcp/#{name}.rb")))
      end
    end
  end

  def snapshot
    Dir[File.join(destination_root, "**/*")].select { |path| File.file?(path) }.sort
      .to_h { |path| [path, File.read(path)] }
  end

  def write(path, content)
    full_path = File.join(destination_root, path)
    FileUtils.mkdir_p(File.dirname(full_path))
    File.write(full_path, content)
  end
