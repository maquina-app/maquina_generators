  test "keeps every error code in one table" do
    run_generator

    errors = controller_errors
    codes = errors.values.map { |error| error[:code] }
    assert_empty [-32700, -32600, -32601, -32602, -32603, -32020, -32021, -32022] - codes
    assert_not_includes codes, -32002
    assert_equal :bad_request, errors[:parse_error][:status]
